// Copies the OSINT lane sources into the agent image build context.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const src = "packages/osint/src";
const dst = "runtime/agent-image/lane";
mkdirSync(dst, { recursive: true });
for (const f of readdirSync(src).filter((f) => f.endsWith(".ts") && !f.includes("test"))) {
  const body = readFileSync(join(src, f), "utf8");
  writeFileSync(join(dst, f), `// GENERATED by scripts/sync-agent-lane.mjs — do not edit\n${body}`);
}
console.log("synced", readdirSync(dst));
